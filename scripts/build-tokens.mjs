// Builds src/ui/tokens/tokens.css from the DTCG JSON files in src/ui/tokens.
//   :root                                      primitives + theme-independent tokens + light theme
//   @media (prefers-color-scheme: dark)        dark theme unless data-theme="light" is set
//   [data-theme="dark"]                        dark theme forced
// It also writes src/ui/tokens/tailwind.css (Tailwind v4 @theme that points at the same variables).
// Run: bun run tokens
import StyleDictionary from "style-dictionary";
import { formattedVariables } from "style-dictionary/utils";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const tokensDir = resolve(root, "src/ui/tokens");
const outFile = resolve(tokensDir, "tokens.css");
const tailwindFile = resolve(tokensDir, "tailwind.css");

const shared = ["primitive", "typography", "spacing", "shape", "layout", "motion"].map((n) => `${tokensDir}/${n}.json`);

async function build(themeFile, onlyFiles) {
  const sd = new StyleDictionary({
    usesDtcg: true,
    log: { verbosity: "silent", warnings: "warn", errors: { brokenReferences: "throw" } },
    source: [...shared, `${tokensDir}/${themeFile}`],
    platforms: {
      css: {
        transformGroup: "css",
        // keep the full path as the variable name: color.page -> --color-page
        files: [],
      },
    },
  });
  const dictionary = await sd.getPlatformTokens("css");
  const tokens = dictionary.allTokens.filter((t) => onlyFiles.some((f) => t.filePath.endsWith(f)));
  const body = formattedVariables({
    format: "css",
    dictionary: { ...dictionary, allTokens: tokens, tokens: dictionary.tokens },
    outputReferences: true,
    usesDtcg: true,
  });
  return body;
}

const sharedFiles = shared.map((p) => p.split("/").pop());
const lightVars = await build("theme.light.json", [...sharedFiles, "theme.light.json"]);
const darkVars = await build("theme.dark.json", ["theme.dark.json"]);

const indent = (s, n) =>
  s
    .split("\n")
    .map((l) => (l ? " ".repeat(n) + l : l))
    .join("\n");

const css = `/* GENERATED by scripts/build-tokens.mjs from src/ui/tokens/*.json. Do not edit by hand. */

:root {
  color-scheme: light dark;
${lightVars}
}

:root[data-theme="light"] {
  color-scheme: light;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${indent(darkVars, 4)}
  }
}

:root[data-theme="dark"] {
  color-scheme: dark;
${indent(darkVars, 2)}
}
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, css);
console.log(`wrote ${outFile} (${css.split("\n").length} lines)`);

// ---- Breakpoint check ----
// Media queries cannot read var(), so Stack and Grid repeat the breakpoint values as literals.
// Fail fast when those literals drift from the tokens, instead of silently changing behavior.
const breakpointNames = ["sm", "md", "lg", "xl"];
const layoutTokens = JSON.parse(readFileSync(`${tokensDir}/layout.json`, "utf8"));
const expected = breakpointNames.map((name) => layoutTokens.breakpoint[name].$value);
const breakpointFiles = [
  resolve(root, "src/ui/components/Stack/Stack.module.css"),
  resolve(root, "src/ui/components/Grid/Grid.module.css"),
];
let breakpointMismatch = false;
for (const file of breakpointFiles) {
  const source = readFileSync(file, "utf8");
  const found = [...source.matchAll(/@media\s*\(min-width:\s*([^)]+)\)/g)].map((m) => m[1].trim());
  if (found.length !== expected.length || found.some((value, i) => value !== expected[i])) {
    breakpointMismatch = true;
    console.error(
      `Breakpoint mismatch in ${file.replace(root + "/", "")}:\n` +
        `  found:    ${found.length ? found.join(", ") : "(none)"}\n` +
        `  expected: ${expected.map((value, i) => `--breakpoint-${breakpointNames[i]} ${value}`).join(", ")}\n` +
        "  Media queries cannot use var(), so update the literal min-width values in the CSS or the tokens in src/ui/tokens/layout.json.",
    );
  }
}
if (breakpointMismatch) process.exit(1);

// ---- Tailwind v4 bridge ----
// `@theme inline` makes utilities (bg-page, text-primary-foreground, rounded-md, shadow-sm, font-emphasis) read our variables
// directly, so light and dark keep working and there is still one source of truth.
const names = (prefix) => [...lightVars.matchAll(new RegExp(`^\\s*(--${prefix}-[a-z0-9-]+):`, "gm"))].map((m) => m[1]);
const line = (n) => `  ${n}: var(${n});`;
const tailwind = `/* GENERATED by scripts/build-tokens.mjs from src/ui/tokens/*.json. Do not edit by hand.
   Usage (Tailwind v4), in your global CSS:
     @import "tailwindcss";
     @import "@/ui/styles/global.css";
     @import "@/ui/tokens/tailwind.css";
   Then: <div class="bg-page text-primary-foreground border border-border-default rounded-lg p-4">
   Keep tokens.css unlayered (do not import it inside @layer): the self-referencing theme variables Tailwind
   emits must lose to the real values in tokens.css.
   To hide Tailwind's default palette so only semantic colors exist, add "--color-*: initial;" at the top of the @theme block below. */

@theme inline {
${names("color").map(line).join("\n")}
${names("radius").map(line).join("\n")}
${names("shadow").map(line).join("\n")}
  --font-sans: var(--font-family-sans);
  --font-mono: var(--font-family-mono);
  --font-emphasis: var(--font-family-emphasis);
}
`;
writeFileSync(tailwindFile, tailwind);
console.log(`wrote ${tailwindFile} (${tailwind.split("\n").length} lines)`);
