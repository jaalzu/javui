import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const require = createRequire(import.meta.url);
const { icons } = require("@phosphor-icons/core");
// The package `exports` map does not expose package.json, so resolve the entry and walk up.
const root = path.dirname(path.dirname(require.resolve("@phosphor-icons/core")));
const names = JSON.parse(readFileSync("src/ui/icons/icons.config.json", "utf8"));

const toJsxAttrs = (s) =>
  s.replace(/\s([a-z]+)-([a-z])([a-z]*)=/g, (_, a, b, c) => ` ${a}${b.toUpperCase()}${c}=`);

const inner = (file) =>
  toJsxAttrs(
    readFileSync(file, "utf8")
      .replace(/^[\s\S]*?<svg[^>]*>/, "")
      .replace(/<\/svg>[\s\S]*$/, "")
      .trim(),
  );

const meta = [];
let out = `// GENERATED by scripts/generate-icons.mjs. Do not edit by hand.\n`;
out += `import { createIcon } from "../components/Icon/createIcon";\n\n`;

for (const name of names) {
  const info = icons.find((i) => i.name === name);
  if (!info) throw new Error(`Unknown Phosphor icon: ${name}`);
  const regular = inner(path.join(root, "assets/regular", `${name}.svg`));
  const fill = inner(path.join(root, "assets/fill", `${name}-fill.svg`));
  out += `export const ${info.pascal_name}Icon = createIcon("${info.pascal_name}", {\n  regular: <>${regular}</>,\n  fill: <>${fill}</>,\n});\n\n`;
  meta.push({
    name,
    component: `${info.pascal_name}Icon`,
    categories: info.categories,
    tags: info.tags,
    weights: ["regular", "fill"],
  });
}

mkdirSync("src/ui/icons", { recursive: true });
writeFileSync("src/ui/icons/icons.generated.tsx", out);
mkdirSync("public/agent", { recursive: true });
writeFileSync("public/agent/icons.json", JSON.stringify(meta, null, 2));

console.log(`generated ${meta.length} icons: src/ui/icons/icons.generated.tsx + public/agent/icons.json`);
